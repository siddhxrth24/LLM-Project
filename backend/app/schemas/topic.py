from datetime import datetime
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field


class TopicContentGenerateRequest(BaseModel):
    """Request payload to generate lesson content for a syllabus topic."""

    regenerate: bool = Field(
        default=False,
        description="Force regeneration even if content was previously generated",
    )


class PracticeQuestion(BaseModel):
    """Practice question with solution and explanation."""

    question: str = Field(..., description="Problem prompt or question")
    answer: str = Field(..., description="Correct answer or concise solution")
    explanation: str = Field(..., description="Detailed rationale explaining the answer")


class LessonContent(BaseModel):
    """Structured lesson schema generated by TeachingService."""

    definition: str = Field(
        ..., description="Precise and formal 1-2 sentence definition"
    )
    explanation: str = Field(
        ..., description="Comprehensive step-by-step conceptual explanation"
    )
    analogy: str = Field(
        ..., description="Intuitive real-world analogy to solidify intuition"
    )
    worked_example: str = Field(
        ..., description="Walkthrough of a concrete example or problem"
    )
    misconceptions: list[str] = Field(
        default_factory=list,
        description="Common mistakes and misconceptions students make",
    )
    practice_questions: list[PracticeQuestion] = Field(
        default_factory=list,
        description="Check-for-understanding practice questions",
    )
    source_supported_points: list[str] = Field(
        default_factory=list,
        description="Key ideas backed directly by course material",
    )
    supplemental_notes: Optional[str] = Field(
        None,
        description="Additional context or background beyond provided course slides",
    )


class SourceReference(BaseModel):
    """Source material citation."""

    source_filename: str
    page_number: Optional[int] = None
    slide_number: Optional[int] = None
    excerpt: Optional[str] = None


class TopicContentResponse(BaseModel):
    """Response containing complete generated lesson content."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    topic_id: int
    topic_name: str
    content: LessonContent
    source_refs: list[SourceReference] = Field(default_factory=list)
    generated_at: datetime
    model_used: str
